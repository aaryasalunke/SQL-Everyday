SELECT S.NAME,S.CITY,C.course_name FROM STUDENT S 
INNER JOIN ENROLLMENT E
ON S.STUDENT_ID = E.STUDENT_ID
INNER JOIN course C
ON C.course_id=E.COURSE_ID
WHERE S.CITY = "PUNE" AND C.course_name="SQL";

------------------ Q12
select S.STUDENT_ID,S.NAME,SUM(AMOUNT_PAID) FROM STUDENT S
INNER JOIN enrollment E
ON E.student_id=S.student_id
INNER JOIN FEE F
ON F.ENROLL_ID=E.ENROLL_ID 
group by S.NAME,S.student_id
ORDER BY SUM(AMOUNT_PAID) desc
LIMIT 1;

