--------- ROW_NUMBER
SELECT EMP_NAME,DEPARTMENT,AMOUNT,ROW_NUMBER() OVER (partition by DEPARTMENT order by AMOUNT) FROM EMPLOYEE;

----------- RANK FUNCTION
SELECT EMP_NAME,DEPARTMENT,AMOUNT,RANK() OVER (order by AMOUNT DESC) FROM EMPLOYEE;

----------- DENSE RANK FUNCTION
SELECT EMP_NAME,DEPARTMENT,AMOUNT,dense_rank() OVER (order by AMOUNT DESC) FROM EMPLOYEE;

----------- SUM() OVER
SELECT EMP_NAME,DEPARTMENT,AMOUNT,SUM(AMOUNT) OVER (partition by DEPARTMENT ORDER BY AMOUNT) FROM EMPLOYEE;

----------- AVG() OVER 
select emp_name,department,amount,avg(amount) over (partition by department order by amount) as average from employee;

----------- min() OVER
SELECT EMP_NAME,DEPARTMENT,AMOUNT,MIN(AMOUNT) OVER (partition by DEPARTMENT ORDER BY AMOUNT) AS MINIMUM_AMT FROM EMPLOYEE;

------------ LAG() FUNCTION 
SELECT EMP_NAME,DEPARTMENT,AMOUNT,LAG(AMOUNT) OVER (ORDER BY AMOUNT) AS LAG_FUN FROM EMPLOYEE;

------------  LEAD() FUNCTION 
SELECT EMP_NAME,DEPARTMENT,AMOUNT,LEAD(AMOUNT) OVER (ORDER BY AMOUNT) AS LEAD_FUN FROM EMPLOYEE;


